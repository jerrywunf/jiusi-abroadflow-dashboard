export const admissionRules = {
  languageRules,
  academicRules,
  testingRules,
  activityRules,
  competitivenessRules,
  schoolSelectionRules,
  reportGenerationRules,
} as const;

export function formatAdmissionRules() {
  return Object.entries(admissionRules)
    .map(([moduleName, rules]) => `${moduleName}:\n${rules.map((rule, index) => `${index + 1}. ${rule}`).join("\n")}`)
    .join("\n\n");
}
